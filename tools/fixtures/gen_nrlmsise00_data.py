"""Convert the BLOCK DATA GTD7BK of NRL's NRLMSISE-00 Fortran (nrlmsise00_sub.for, from the
NASA CCMC ModelWeb archive) into Rust tables laid out exactly like the Fortran COMMON blocks.

    python3 -I tools/fixtures/gen_nrlmsise00_data.py path/to/nrlmsise00_sub.for > crates/sim-core/src/nrlmsise00_data.rs
"""
import re
import sys

src = open(sys.argv[1]).read().splitlines()
start = next(i for i, l in enumerate(src) if l.strip().startswith("BLOCK DATA GTD7BK"))
body = []
for l in src[start:]:
    if l[:1] in ("C", "c", "*") and not l.startswith("     *") and l[:1] != " ":
        continue
    body.append(l)
    if l.strip() == "END":
        break
# Join continuation lines (column 6 non-blank).
stmts = []
for l in body:
    if len(l) > 5 and l[5] not in (" ", "0") and stmts:
        stmts[-1] += " " + l[6:]
    else:
        stmts.append(l[6:] if len(l) > 6 else "")

arrays = {}
for s in stmts:
    s = s.strip()
    if not s.upper().startswith("DATA"):
        continue
    for name, vals in re.findall(r"([A-Z0-9]+)\s*/([^/]*)/", s[4:], re.I):
        out = []
        for tok in vals.split(","):
            tok = tok.strip()
            if not tok or tok.startswith("'"):
                continue
            if "*" in tok:
                n, v = tok.split("*")
                out += [float(v.replace("D", "E"))] * int(n)
            else:
                out.append(float(tok.replace("D", "E")))
        if out:
            arrays[name.upper()] = arrays.get(name.upper(), []) + out

# COMMON/PARM7/ member order.
parm7 = ("PT1 PT2 PT3 PA1 PA2 PA3 PB1 PB2 PB3 PC1 PC2 PC3 PD1 PD2 PD3 PE1 PE2 PE3 PF1 PF2 PF3 "
         "PG1 PG2 PG3 PH1 PH2 PH3 PI1 PI2 PI3 PJ1 PJ2 PJ3 PK1 PL1 PL2 PM1 PM2 PN1 PN2 PO1 PO2 "
         "PP1 PP2 PQ1 PQ2 PR1 PR2 PS1 PS2 PU1 PU2 PV1 PV2 PW1 PW2 PX1 PX2 PY1 PY2 PZ1 PZ2 PAA1 PAA2").split()
flat = []
for n in parm7:
    a = arrays[n]
    assert len(a) == 50, (n, len(a))
    flat += a
assert len(flat) == 150 + 150 * 9 + 150 + 50 + 400 + 1000 + 100
off = 0
def take(n):
    global off
    v = flat[off:off + n]
    off += n
    return v
PT = take(150); PD = take(150 * 9); PS = take(150); PDL = take(50); PTL = take(400); PMA = take(1000); SAM = take(100)
PTM = arrays["PTM"]; PDM = arrays["PDM"]; PAVGM = arrays["PAVGM"]
assert len(PTM) == 10 and len(PDM) == 80 and len(PAVGM) == 10

def emit(name, vals, doc):
    print(f"/// {doc}")
    print(f"pub(crate) const {name}: [f64; {len(vals)}] = [")
    for i in range(0, len(vals), 6):
        print("    " + ", ".join(f"{v:e}" for v in vals[i:i + 6]) + ",")
    print("];")

print("// @generated by tools/fixtures/gen_nrlmsise00_data.py from NRL's nrlmsise00_sub.for")
print("// (BLOCK DATA GTD7BK, MSISE-00 01-FEB-02). Do not edit. Arrays keep the Fortran")
print("// column-major layout: X(i, j) is at index (j-1)*rows + (i-1).")
print("#![allow(clippy::excessive_precision, clippy::approx_constant)]")
emit("PT", PT, "PT(150): temperature")
emit("PD", PD, "PD(150, 9): He, O, N2, TLB, O2, Ar, H, N, hot O")
emit("PS", PS, "PS(150): S parameter")
emit("PDL", PDL, "PDL(25, 2): turbopause corrections")
emit("PTL", PTL, "PTL(100, 4): lower boundary temperatures")
emit("PMA", PMA, "PMA(100, 10): mesosphere")

emit("PTM", PTM, "PTM(10): lower boundary")
emit("PDM", PDM, "PDM(10, 8): lower boundary densities")

