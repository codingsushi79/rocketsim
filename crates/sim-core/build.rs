//! Generates tables from committed data files, so each data file is the single
//! source of truth:
//! - leap seconds from the IERS `Leap_Second.dat` (data/time/Leap_Second.dat)
//! - IAU WGCCRE rotation models from NAIF `pck00011.tpc` (data/pck/pck00011.tpc)
//! - Earth orientation parameters from IERS `finals2000A.all` (data/eop/finals2000A.all)

#[path = "src/naif_text_kernel.rs"]
#[allow(dead_code)]
mod naif_text_kernel;

use std::{env, fs, path::Path};

const MONTHS: [&str; 12] = [
    "january",
    "february",
    "march",
    "april",
    "may",
    "june",
    "july",
    "august",
    "september",
    "october",
    "november",
    "december",
];

/// Days from 1970-01-01 in the proleptic Gregorian calendar (H. Hinnant,
/// "chrono-Compatible Low-Level Date Algorithms", `days_from_civil`).
/// Duplicated from `src/time.rs` because build scripts cannot use the crate.
fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = (if y >= 0 { y } else { y - 399 }) / 400;
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

const MJD_OF_UNIX_EPOCH: i64 = 40_587;

/// Bodies whose IAU rotation model is generated (the v1 body list).
const IAU_BODIES: [i32; 27] = [
    10, 199, 299, 399, 301, 499, 401, 402, 599, 501, 502, 503, 504, 699, 601, 602, 603, 604, 605,
    606, 608, 799, 899, 801, 999, 2_000_001, 2_000_004,
];

fn fmt_list(v: &[f64]) -> String {
    let items: Vec<String> = v.iter().map(|x| format!("{x:?}")).collect();
    format!("&[{}]", items.join(", "))
}

fn generate_iau_models() {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/pck/pck00011.tpc");
    println!("cargo:rerun-if-changed={}", src.display());
    let k = naif_text_kernel::parse(&fs::read_to_string(&src).expect("read pck00011.tpc"));
    let get3 = |key: &str| -> [f64; 3] {
        let v = k
            .get(key)
            .unwrap_or_else(|| panic!("{key} missing from pck00011.tpc"));
        let mut a = [0.0; 3];
        for (i, x) in v.iter().take(3).enumerate() {
            a[i] = *x;
        }
        a
    };
    let mut out = String::from(
        "// @generated by build.rs from data/pck/pck00011.tpc (IAU WGCCRE 2015). Do not edit.\n\
         // Kernel coefficients such as Triton's -6.28 are data, not approximations of τ.\n\
         #[allow(clippy::approx_constant)]\n\
         pub(crate) const IAU_MODELS: &[IauModel] = &[\n",
    );
    for id in IAU_BODIES {
        let ra = get3(&format!("BODY{id}_POLE_RA"));
        let dec = get3(&format!("BODY{id}_POLE_DEC"));
        let pm = get3(&format!("BODY{id}_PM"));
        let nut = |what: &str| {
            k.get(&format!("BODY{id}_NUT_PREC_{what}"))
                .cloned()
                .unwrap_or_default()
        };
        let (nut_ra, nut_dec, nut_pm) = (nut("RA"), nut("DEC"), nut("PM"));
        // Planets and satellites take their angles from the system barycenter (id / 100).
        let bary = if (100..1000).contains(&id) {
            id / 100
        } else {
            -1
        };
        let angles = k
            .get(&format!("BODY{bary}_NUT_PREC_ANGLES"))
            .cloned()
            .unwrap_or_default();
        let degree = k
            .get(&format!("BODY{bary}_MAX_PHASE_DEGREE"))
            .map_or(1, |v| v[0] as usize);
        let per = degree + 1;
        assert_eq!(angles.len() % per, 0, "BODY{bary}_NUT_PREC_ANGLES length");
        let n_angles = angles.len() / per;
        for (what, v) in [("RA", &nut_ra), ("DEC", &nut_dec), ("PM", &nut_pm)] {
            assert!(
                v.len() <= n_angles,
                "BODY{id}_NUT_PREC_{what} has more terms than angles"
            );
        }
        out.push_str(&format!(
            "    IauModel {{ id: {id}, ra: {ra:?}, dec: {dec:?}, pm: {pm:?}, nut_ra: {}, nut_dec: {}, nut_pm: {}, angles: {}, angle_terms: {per} }},\n",
            fmt_list(&nut_ra), fmt_list(&nut_dec), fmt_list(&nut_pm), fmt_list(&angles)
        ));
    }
    out.push_str("];\n");
    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("iau_models.rs");
    fs::write(dest, out).unwrap();
}

fn main() {
    generate_iau_models();
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/time/Leap_Second.dat");
    println!("cargo:rerun-if-changed={}", src.display());
    let text = fs::read_to_string(&src).expect("read data/time/Leap_Second.dat");

    let mut rows = Vec::new();
    let mut expires_mjd = None;
    for line in text.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix('#') {
            let rest = rest.trim();
            if let Some(date) = rest.strip_prefix("File expires on") {
                let parts: Vec<&str> = date.split_whitespace().collect();
                assert_eq!(parts.len(), 3, "bad expiry line: {line}");
                let d: i64 = parts[0].parse().unwrap();
                let m = MONTHS
                    .iter()
                    .position(|n| n.eq_ignore_ascii_case(parts[1]))
                    .expect("month name") as i64
                    + 1;
                let y: i64 = parts[2].parse().unwrap();
                expires_mjd = Some(days_from_civil(y, m, d) + MJD_OF_UNIX_EPOCH);
            }
            continue;
        }
        if t.is_empty() {
            continue;
        }
        let f: Vec<&str> = t.split_whitespace().collect();
        assert_eq!(f.len(), 5, "bad leap second row: {line}");
        let mjd: f64 = f[0].parse().unwrap();
        assert_eq!(mjd.fract(), 0.0);
        let (d, m, y): (i64, i64, i64) = (
            f[1].parse().unwrap(),
            f[2].parse().unwrap(),
            f[3].parse().unwrap(),
        );
        let mjd = mjd as i64;
        assert_eq!(
            days_from_civil(y, m, d) + MJD_OF_UNIX_EPOCH,
            mjd,
            "MJD/date mismatch: {line}"
        );
        let dat: i64 = f[4].parse().unwrap();
        rows.push((mjd, dat));
    }
    assert!(rows.len() >= 28, "leap second table looks truncated");
    assert!(rows.windows(2).all(|w| w[0].0 < w[1].0), "rows not sorted");
    let expires_mjd = expires_mjd.expect("expiry line");

    let mut out = String::from(
        "// @generated by build.rs from data/time/Leap_Second.dat. Do not edit.\n\
         /// (UTC MJD from which the offset applies, TAI − UTC in whole seconds).\n\
         pub(crate) const LEAP_SECONDS: &[(i64, i64)] = &[\n",
    );
    for (mjd, dat) in &rows {
        out.push_str(&format!("    ({mjd}, {dat}),\n"));
    }
    out.push_str("];\n");
    out.push_str(&format!(
        "/// UTC MJD on which the IERS file expires. Later dates are provisional.\n\
         pub(crate) const LEAP_TABLE_EXPIRES_MJD: i64 = {expires_mjd};\n"
    ));
    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("leap_seconds.rs");
    fs::write(dest, out).unwrap();
    generate_eop(&rows);
}

/// IERS finals2000A (Bulletin A, IAU 2000 nutation): fixed-column format per
/// https://maia.usno.navy.mil/ser7/readme.finals2000A. Emits daily rows of polar
/// motion and UT1−TAI. UT1−TAI is used instead of UT1−UTC because it is continuous
/// across leap seconds, so it can be interpolated.
fn generate_eop(leap: &[(i64, i64)]) {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/eop/finals2000A.all");
    println!("cargo:rerun-if-changed={}", src.display());
    let text = fs::read_to_string(&src).expect("read data/eop/finals2000A.all");
    let col = |line: &str, a: usize, b: usize| line.get(a - 1..b).unwrap_or("").trim().to_string();
    let mut first = None;
    let mut last_observed = None;
    let mut rows: Vec<(i64, i64, i64)> = Vec::new();
    for line in text.lines() {
        let ut1_flag = col(line, 58, 58);
        if ut1_flag != "I" && ut1_flag != "P" {
            continue;
        }
        let mjd: f64 = col(line, 8, 15).parse().expect("MJD");
        assert_eq!(mjd.fract(), 0.0);
        let mjd = mjd as i64;
        let xp: f64 = col(line, 19, 27).parse().expect("PM-x");
        let yp: f64 = col(line, 38, 46).parse().expect("PM-y");
        let ut1_utc: f64 = col(line, 59, 68).parse().expect("UT1-UTC");
        let dat = leap
            .iter()
            .rev()
            .find(|(m, _)| *m <= mjd)
            .expect("EOP before 1972")
            .1;
        if let Some(f) = first {
            assert_eq!(
                mjd,
                f + rows.len() as i64,
                "EOP rows not consecutive at MJD {mjd}"
            );
        }
        first.get_or_insert(mjd);
        if ut1_flag == "I" {
            last_observed = Some(mjd);
        }
        // µas, µas, 0.1 µs: below the published precision (1e-6″, 1e-7 s).
        rows.push((
            (xp * 1e6).round() as i64,
            (yp * 1e6).round() as i64,
            ((ut1_utc - dat as f64) * 1e7).round() as i64,
        ));
    }
    let first = first.expect("EOP rows");
    let mut out = format!(
        "// @generated by build.rs from data/eop/finals2000A.all (IERS Bulletin A). Do not edit.\n\
         /// UTC MJD of the first row.\n\
         pub(crate) const EOP_FIRST_MJD: i64 = {first};\n\
         /// Last UTC MJD with observed (not predicted) UT1.\n\
         pub(crate) const EOP_LAST_OBSERVED_MJD: i64 = {};\n\
         /// Daily (x_p [µas], y_p [µas], UT1−TAI [0.1 µs]) from EOP_FIRST_MJD, at 0h UTC.\n\
         pub(crate) const EOP: &[(i32, i32, i32)] = &[\n",
        last_observed.expect("observed rows")
    );
    for (x, y, u) in &rows {
        out.push_str(&format!("({x},{y},{u}),"));
    }
    out.push_str("\n];\n");
    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("eop.rs");
    fs::write(dest, out).unwrap();
}
